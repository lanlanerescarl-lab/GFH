<?php

declare(strict_types=1);

namespace Gfh\Core\View;

/**
 * Builds the public address of an asset for one app of one organization.
 * An organization's own published file (public/assets/orgs/{slug}/{app}/...) wins over the shared one
 * (public/assets/{app}/...), the same override rule the templates follow. Both folders are written by
 * bin/publish-assets.php; templates themselves are never web-visible.
 */
final class AssetUrls
{
    /** One folder or file name: starts with a letter, digit, underscore or hyphen, so ".." and hidden names never match. */
    public const SEGMENT = '[A-Za-z0-9_-][A-Za-z0-9._-]*';

    public function __construct(
        private readonly string $publicPath,
        private readonly string $basePath,
        private readonly string $organizationSlug,
        private readonly string $app,
    ) {
        TemplateLocator::assertSlug($organizationSlug);
        if (!in_array($app, TemplateLocator::APPS, true)) {
            throw new \InvalidArgumentException(sprintf('Unknown app "%s".', $app));
        }
    }

    /** An asset of this app, for example url('css/app.css'). */
    public function url(string $path): string
    {
        $this->assertPath($path);

        $own = 'assets/orgs/' . $this->organizationSlug . '/' . $this->app . '/' . $path;
        if (is_file($this->publicPath . '/' . $own)) {
            return $this->basePath . '/' . $own;
        }

        return $this->basePath . '/assets/' . $this->app . '/' . $path;
    }

    /** An asset shared by all apps, for example shared('css/tokens.css'). */
    public function shared(string $path): string
    {
        $this->assertPath($path);

        return $this->basePath . '/assets/' . $path;
    }

    /** The organization's branding stylesheet (generated by BrandingController). */
    public function branding(): string
    {
        return $this->basePath . '/' . $this->organizationSlug . '/branding.css';
    }

    private function assertPath(string $path): void
    {
        if (preg_match('#^' . self::SEGMENT . '(/' . self::SEGMENT . ')*$#D', $path) !== 1) {
            throw new \InvalidArgumentException('That is not a valid asset path.');
        }
    }
}
